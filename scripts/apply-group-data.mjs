async function applyGroupData() {
  try {
    console.log('Starting to apply group data...');
    
    for (const data of groupData) {
      const user = await prisma.user.findFirst({
        where: {
          name: {
            equals: data.name,
            mode: 'insensitive',
          },
        },
      });
      
      if (user) {
        await prisma.user.update({
          where: { id: user.id },
          data: { groups: data.groups },
        });
        console.log(`Updated: ${data.name} → ${data.groups}`);
      } else {
        console.log(`Not found: ${data.name}`);
      }
    }
    
    console.log('Group data applied successfully!');
  } catch (error) {
    console.error('Error applying group data:', error);
  } finally {
    await prisma.$disconnect();
  }
}

